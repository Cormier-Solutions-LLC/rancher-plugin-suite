import assert from 'node:assert/strict';
import { reactive, nextTick } from 'vue';
import { namespaceContext, contextMatches, connectNamespaceContext, setNamespaceContext } from '../pkg/simple-network-manager/data/namespace-context';
setNamespaceContext(['ns://ai']);
assert.equal(contextMatches('ai'),true);
assert.equal(contextMatches('omada'),false);
assert.equal(contextMatches('',true),true,'Shared presets remain available within a selected namespace.');
setNamespaceContext(['all://system']);
assert.equal(contextMatches('cattle-system'),true);
assert.equal(contextMatches('ai'),false);
setNamespaceContext(['namespaced://true','namespaced://false']);
assert.deepEqual(namespaceContext.value,['namespaced://false']);
assert.equal(contextMatches('ai'),false);
assert.equal(contextMatches(''),true);
const getters=reactive({activeNamespaceFilters:['ns://ai'],activeNamespaceCache:{ai:true},allNamespaces:[{id:'ai'}]});
let committed:any;
connectNamespaceContext({getters,commit:(name:string,payload:any)=>{committed={name,payload};getters.activeNamespaceFilters=payload.filters;}});
assert.deepEqual(namespaceContext.value,['ns://ai']);
getters.activeNamespaceFilters=['all://user'];await nextTick();
assert.deepEqual(namespaceContext.value,['all://user'],'Native context updates page filters.');
setNamespaceContext(['ns://omada']);
assert.deepEqual(committed,{name:'updateNamespaces',payload:{filters:['ns://omada']}},'Page context updates native picker.');
console.log('Namespace checks passed: shared Global presets, system/user classification, cluster-resource scope, and two-way native store synchronization.');
