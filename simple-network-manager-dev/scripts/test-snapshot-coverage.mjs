import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { coverageEntries, assessCoverage, uncoveredEntries } from '../pkg/simple-network-manager/config/snapshot-coverage.mjs';
const now = Date.parse('2026-10-11T12:00:00Z');
const expected = [{id:'a',digest:'one'},{id:'b',digest:'two'}];
const snap = (coverage,age=0) => ({coverage,createdAt:new Date(now-age).toISOString()});
assert.equal(assessCoverage(expected,[],now).tone,'error');
assert.equal(assessCoverage(expected,[snap(expected,7*86400000)],now).tone,'error');
assert.equal(assessCoverage(expected,[snap(expected,-1)],now).tone,'error');
assert.equal(assessCoverage(expected,[snap([expected[0]])],now).tone,'warning');
assert.equal(assessCoverage(expected,[snap([{id:'a',digest:'changed'},expected[1]])],now).tone,'warning');
assert.equal(assessCoverage(expected,[snap([expected[0]]),snap([expected[1]])],now).tone,'success');
const resource = {apiVersion:'networking.k8s.io/v1',kind:'Ingress',metadata:{name:'web',namespace:'apps'},spec:{rules:[{host:'example.com'}]}};
const entries = coverageEntries({routeManifests:[resource],observedServiceReferences:[{name:'web',namespace:'apps',ports:[{port:80}]}]});
const digest = value => createHash('sha256').update(value).digest('hex');
assert.equal(entries.length,2);
assert.equal(digest(entries[0].value),digest(coverageEntries({routeManifests:[{spec:resource.spec,metadata:resource.metadata,kind:resource.kind,apiVersion:resource.apiVersion}]})[0].value));
assert.notEqual(digest(entries[0].value),digest(coverageEntries({routeManifests:[{...resource,spec:{rules:[{host:'changed.com'}]}}]})[0].value));
const secret={apiVersion:'v1',kind:'Secret',metadata:{name:'web-tls',namespace:'apps'},data:{password:'ZmFrZQ=='}};
assert.equal(coverageEntries({routeManifests:[secret]}).length,1);
const tlsRoute={...resource,spec:{...resource.spec,tls:[{secretName:'web-tls'}]}};
const absent=coverageEntries({routeManifests:[tlsRoute]});
assert.equal(absent.find(entry=>entry.id.includes('/Secret/')).incomplete,true);
assert.equal(coverageEntries({routeManifests:[tlsRoute,secret]}).some(entry=>entry.incomplete),false);
console.log('Snapshot coverage: current versions, partial coverage, union, age, future dates and captured Secret coverage and missing-credential gaps passed.');

assert.deepEqual(uncoveredEntries(expected,[snap(expected)],now),[],"Complete matching coverage stays hidden.");
assert.equal(uncoveredEntries(expected,[snap([expected[0]])],now)[0].status,"Missing");
assert.equal(uncoveredEntries(expected,[snap([{id:"a",digest:"changed"},expected[1]])],now)[0].status,"Changed");
assert.equal(uncoveredEntries(expected,[snap(expected,8*86400000)],now)[0].status,"Outdated");
assert.equal(uncoveredEntries(expected,[snap([{...expected[0],createdAt:new Date(now-8*86400000).toISOString()},expected[1]])],now)[0].status,"Outdated","Merging old items does not refresh their capture dates.");
